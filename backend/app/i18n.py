def lang_of(lang: str | None) -> str:
    return lang if lang in LANGS else "en"


def question(qid: str, lang: str, text: str, why: str, options: list[str]) -> dict:
    """Display text for a question; `options` stays English (the values sent back)."""
    t = Q.get(lang, {}).get(qid)
    if not t:
        return {"text": text, "why": why, "option_labels": options}
    labels = t[2] if len(t[2]) == len(options) else options
    return {"text": t[0], "why": t[1], "option_labels": labels}


def answer_label(qid: str, value: str, lang: str, options: list[str]) -> str:
    t = Q.get(lang, {}).get(qid)
    if t and value in options and len(t[2]) == len(options):
        return t[2][options.index(value)]
    return value


def offence(oid: str, lang: str, default: str) -> str:
    if lang == "en" or oid not in OFFENCE:
        return default
    return OFFENCE[oid][0 if lang == "hi" else 1]


def step(key: str, lang: str, **fmt) -> dict:
    title, detail = STEPS[lang][key]
    zero = STEPS[lang]["zero"] if fmt.pop("show_zero", False) else ""
    return {"id": key, "title": title, "detail": detail.format(zero=zero, **fmt)}


def helpline(key: str, lang: str) -> str:
    return HELPLINES[lang][key]


def regime_reason(regime: dict, lang: str) -> str | None:
    if lang == "en":
        return regime.get("reason")
    d = regime.get("decision")
    key = regime.get("law") if d == "decided" else d
    return REGIME[lang].get(key, regime.get("reason"))


def advice(level_key: str, lang: str, date: str | None) -> tuple[str, str]:
    t = ADVICE[lang]
    return t[level_key].format(d=date), t["procedure"]
